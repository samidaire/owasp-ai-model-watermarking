"""Circom + SnarkJS Groth16 backend (ZK-01, ZK-04, ZK-05).

Toolchain lookup (override with environment variables):
  SIGIL_CIRCUITS  folder holding ownership.circom and node_modules (default: <repo>/circuits)
  SIGIL_CIRCOM    circom 2 compiler (default: <repo>/tools/bin/circom[.exe], then PATH)
  SIGIL_NODE      node executable (default: PATH)
Build outputs go to <circuits>/build (gitignored); public verification keys and setup transcripts to
<circuits>/keys (committed: verifiers need nothing else).
"""
from __future__ import annotations

import hashlib
import json
import os
import secrets
import shutil
import subprocess
import tempfile
import time
from dataclasses import dataclass
from pathlib import Path

from ..protocol import PRG_BITS, Config
from .ptau import get_ptau, power_for


class ZkError(RuntimeError):
    pass


def _repo_root() -> Path:
    here = Path(__file__).resolve()
    for p in here.parents:
        if (p / "circuits" / "ownership.circom").exists():
            return p
    return Path.cwd()


def circuits_dir() -> Path:
    d = Path(os.environ.get("SIGIL_CIRCUITS") or _repo_root() / "circuits")
    if not (d / "ownership.circom").exists():
        raise ZkError(f"ownership.circom not found in {d}; set SIGIL_CIRCUITS")
    return d


def _circom() -> str:
    env = os.environ.get("SIGIL_CIRCOM")
    if env:
        return env
    for name in ("circom.exe", "circom"):
        p = _repo_root() / "tools" / "bin" / name
        if p.exists():
            return str(p)
    found = shutil.which("circom")
    if not found:
        raise ZkError("circom compiler not found: install circom 2.2.x or set SIGIL_CIRCOM")
    return found


def _snarkjs() -> list[str]:
    cli = circuits_dir() / "node_modules" / "snarkjs" / "build" / "cli.cjs"
    if not cli.exists():
        raise ZkError(f"snarkjs not installed: run `npm install` in {circuits_dir()}")
    return [os.environ.get("SIGIL_NODE") or shutil.which("node") or "node", str(cli)]


def _run(cmd: list[str], cwd: Path | None = None, timeout: int = 3600) -> str:
    r = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, timeout=timeout)
    out = (r.stdout or "") + (r.stderr or "")
    if r.returncode != 0:
        raise ZkError(f"command failed ({r.returncode}): {' '.join(cmd[:4])} ...\n{out[-2000:]}")
    return out


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


# ------------------------------------------------------------------ circuit variants
def circuit_name(cfg: Config) -> str:
    return f"ownership_T{cfg.T}_M{cfg.M}_E{cfg.max_err}_W{cfg.w_bits}"


def main_source(cfg: Config) -> str:
    return (
        "pragma circom 2.1.9;\n"
        f"// Generated by sigil.zk.circom for config T={cfg.T}, M={cfg.M}, max_err={cfg.max_err}, w_bits={cfg.w_bits}.\n"
        'include "../ownership.circom";\n'
        "component main {public [pk_hash, config_hash, commitment, w_hash, nonce]} = "
        f"Ownership({cfg.T}, {cfg.M}, {cfg.w_bits}, {cfg.sum_bits}, {cfg.max_err}, {PRG_BITS});\n"
    )


@dataclass(frozen=True)
class Artifacts:
    name: str
    build: Path

    @property
    def r1cs(self) -> Path: return self.build / f"{self.name}.r1cs"
    @property
    def wasm(self) -> Path: return self.build / f"{self.name}_js" / f"{self.name}.wasm"
    @property
    def zkey(self) -> Path: return self.build / f"{self.name}.zkey"
    @property
    def vkey(self) -> Path: return circuits_dir() / "keys" / f"{self.name}.vkey.json"
    @property
    def transcript(self) -> Path: return circuits_dir() / "keys" / f"{self.name}.setup.json"


def artifacts(cfg: Config) -> Artifacts:
    return Artifacts(circuit_name(cfg), circuits_dir() / "build")


def compile_circuit(cfg: Config, force: bool = False) -> Artifacts:
    a = artifacts(cfg)
    a.build.mkdir(parents=True, exist_ok=True)
    src = a.build / f"main_{a.name}.circom"
    text = main_source(cfg)
    stamp = a.build / f"{a.name}.srchash"
    digest = hashlib.sha256((text + (circuits_dir() / "ownership.circom").read_text()).encode()).hexdigest()
    if not force and a.r1cs.exists() and a.wasm.exists() and stamp.exists() and stamp.read_text() == digest:
        return a
    src.write_text(text)
    _run([_circom(), str(src), "--O2", "--r1cs", "--wasm", "-l", str(circuits_dir() / "node_modules"),
          "-o", str(a.build)], timeout=3600)
    # circom names outputs after the main file
    for ext in (".r1cs",):
        (a.build / f"main_{a.name}{ext}").replace(a.r1cs)
    js = a.build / f"main_{a.name}_js"
    if (a.build / f"{a.name}_js").exists():
        shutil.rmtree(a.build / f"{a.name}_js")
    js.rename(a.build / f"{a.name}_js")
    (a.build / f"{a.name}_js" / f"main_{a.name}.wasm").replace(a.wasm)
    stamp.write_text(digest)
    return a


def r1cs_info(a: Artifacts) -> dict:
    out = _run([*_snarkjs(), "r1cs", "info", str(a.r1cs)])
    info = {}
    for line in out.splitlines():
        for key in ("# of Constraints", "# of Private Inputs", "# of Public Inputs", "# of Wires"):
            if key in line:
                info[key.strip("# ").lower().replace(" ", "_")] = int(line.rsplit(":", 1)[1])
    return info


def setup(cfg: Config, entropy: str | None = None, contributor: str = "sigil project setup") -> dict:
    """Groth16 phase-2 setup on the public Powers of Tau, plus one contribution of our own (ZK-04)."""
    a = compile_circuit(cfg)
    info = r1cs_info(a)
    k = power_for(info["of_constraints"], info.get("of_public_inputs", 0))
    ptau = get_ptau(k)
    z0 = a.build / f"{a.name}_0000.zkey"
    t0 = time.time()
    _run([*_snarkjs(), "groth16", "setup", str(a.r1cs), str(ptau), str(z0)])
    entropy = entropy or secrets.token_hex(32)       # toxic waste: generated here and never stored
    out = _run([*_snarkjs(), "zkey", "contribute", str(z0), str(a.zkey), f"--name={contributor}", f"-e={entropy}"])
    del entropy
    z0.unlink()
    verify_out = _run([*_snarkjs(), "zkey", "verify", str(a.r1cs), str(ptau), str(a.zkey)])
    if "ZKey Ok!" not in verify_out:
        raise ZkError("zkey verification failed:\n" + verify_out[-1500:])
    a.vkey.parent.mkdir(parents=True, exist_ok=True)
    _run([*_snarkjs(), "zkey", "export", "verificationkey", str(a.zkey), str(a.vkey)])
    contribution = next((ln.split(":", 1)[1].strip() for ln in out.splitlines() if "Contribution Hash" in ln), None)
    transcript = {
        "circuit": a.name, "config": cfg.to_dict(), "constraints": info["of_constraints"],
        "ptau": ptau.name, "ptau_blake2b": None, "r1cs_sha256": sha256_file(a.r1cs),
        "zkey_sha256": sha256_file(a.zkey), "vkey_sha256": sha256_file(a.vkey),
        "phase2_contributor": contributor, "phase2_contribution_hash": contribution,
        "setup_seconds": round(time.time() - t0, 1),
        "trust": "Groth16: secure if at least one Powers of Tau contributor and the phase-2 contributor "
                 "destroyed their randomness. Phase-2 entropy was generated in memory and not stored.",
    }
    from .ptau import blake2b_file
    transcript["ptau_blake2b"] = blake2b_file(ptau)
    a.transcript.write_text(json.dumps(transcript, indent=2))
    return transcript


def prove(cfg: Config, circuit_input: dict, workdir: Path | None = None) -> tuple[dict, list[str], dict]:
    """Generate a Groth16 proof. Returns (proof, public_signals, timings)."""
    a = artifacts(cfg)
    if not (a.wasm.exists() and a.zkey.exists()):
        raise ZkError(f"circuit {a.name} is not set up: run sigil.zk.circom.setup(cfg) first")
    with tempfile.TemporaryDirectory(dir=workdir) as tmp:
        tmp = Path(tmp)
        inp, wtns, proof_p, pub_p = tmp / "input.json", tmp / "w.wtns", tmp / "proof.json", tmp / "public.json"
        inp.write_text(json.dumps(circuit_input))
        t0 = time.time()
        try:
            _run([*_snarkjs(), "wtns", "calculate", str(a.wasm), str(inp), str(wtns)])
        except ZkError as e:
            raise ZkError("the witness does not satisfy the circuit (wrong seed/commitment, model mismatch, "
                          "or too many watermark bits wrong)") from e
        t1 = time.time()
        _run([*_snarkjs(), "groth16", "prove", str(a.zkey), str(wtns), str(proof_p), str(pub_p)])
        t2 = time.time()
        return (json.loads(proof_p.read_text()), json.loads(pub_p.read_text()),
                {"witness_s": round(t1 - t0, 3), "prove_s": round(t2 - t1, 3)})


def verify_snark(vkey_path: Path, proof: dict, public: list[str]) -> bool:
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        (tmp / "proof.json").write_text(json.dumps(proof))
        (tmp / "public.json").write_text(json.dumps(public))
        r = subprocess.run([*_snarkjs(), "groth16", "verify", str(vkey_path), str(tmp / "public.json"),
                            str(tmp / "proof.json")], capture_output=True, text=True, timeout=600)
        return r.returncode == 0 and "OK!" in (r.stdout + r.stderr)
