"""Poseidon hash over BN254, bit-exact with circomlib's poseidon.circom and circomlibjs.

This is the reference (unoptimised) permutation from circomlibjs/src/poseidon_reference.js with the
same round constants and MDS matrices (data/poseidon_constants.json, see data/README.md). It
outputs the same values as circomlib's optimised circuit; sdk/tests/test_poseidon.py checks that
against vectors generated by circomlibjs.
"""
import json
from functools import lru_cache
from importlib.resources import files

from .field import P

N_ROUNDS_F = 8
N_ROUNDS_P = (56, 57, 56, 60, 60, 63, 64, 63, 60, 66, 60, 65, 70, 60, 64, 68)
MAX_INPUTS = len(N_ROUNDS_P)


@lru_cache(maxsize=1)
def _constants():
    data = json.loads(files("sigil.data").joinpath("poseidon_constants.json").read_text(encoding="utf-8"))
    C = tuple(tuple(int(x, 16) for x in row) for row in data["C"])
    M = tuple(tuple(tuple(int(x, 16) for x in r) for r in m) for m in data["M"])
    return C, M


def poseidon(inputs) -> int:
    """Poseidon hash of 1..16 field elements (ints in [0, P)). Returns a field element."""
    inputs = [int(x) for x in inputs]
    n = len(inputs)
    if not 1 <= n <= MAX_INPUTS:
        raise ValueError(f"poseidon takes 1..{MAX_INPUTS} inputs, got {n}")
    if any(not 0 <= x < P for x in inputs):
        raise ValueError("poseidon inputs must be canonical field elements in [0, P)")
    t = n + 1
    C, M = _constants()
    c, m, rp = C[t - 2], M[t - 2], N_ROUNDS_P[t - 2]
    half_f = N_ROUNDS_F // 2
    state = [0, *inputs]
    for r in range(N_ROUNDS_F + rp):
        state = [(a + c[r * t + i]) % P for i, a in enumerate(state)]
        if r < half_f or r >= half_f + rp:
            state = [pow(a, 5, P) for a in state]
        else:
            state[0] = pow(state[0], 5, P)
        state = [sum(m[i][j] * state[j] for j in range(t)) % P for i in range(t)]
    return state[0]
